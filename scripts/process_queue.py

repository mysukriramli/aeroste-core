"""Automated batch processor: transforms input/ documents into output/ compliant STE files."""

import os
import re
from pathlib import Path
from app.engine import evaluate_ste_metrics, STE_LEXICON, GENERAL_CLUTTER_LEXICON

INPUT_DIR = Path("input")
OUTPUT_DIR = Path("output")


def apply_lexical_replacements(text: str, profile: str = "aerospace_ste") -> str:
    """Deterministically substitute non-approved terms using the controlled lexicon."""
    lexicon = STE_LEXICON if profile == "aerospace_ste" else GENERAL_CLUTTER_LEXICON
    transformed = text

    # Sort keys by length descending to prevent partial token replacement
    sorted_terms = sorted(lexicon.keys(), key=len, reverse=True)
    for unapproved in sorted_terms:
        approved = lexicon[unapproved]
        # Match standalone words/phrases case-insensitively
        pattern = re.compile(r"\b" + re.escape(unapproved) + r"\b", re.IGNORECASE)

        def replace_match(match):
            original = match.group(0)
            if original.isupper():
                return approved.upper()
            if original[0].isupper():
                return approved.capitalize()
            return approved

        transformed = pattern.sub(replace_match, transformed)

    if profile == "aerospace_ste":
        # Remove semicolons by converting them to periods
        transformed = transformed.replace(";", ".")
        # Remove exclamation marks
        transformed = transformed.replace("!", ".")

    return transformed


def process_file(file_path: Path):
    """Analyze and transform a single file from input/ to output/."""
    print(f"\n[QUEUE] Ingesting: {file_path.name}")
    raw_content = file_path.read_text(encoding="utf-8").strip()
    if not raw_content:
        print(f"[SKIP] Empty file: {file_path.name}")
        return

    # Check for profile directive at the top of the file (e.g. <!-- profile: technical -->)
    profile = "aerospace_ste"
    match = re.search(r"<!--\s*profile:\s*([a-zA-Z_]+)\s*-->", raw_content)
    if match:
        extracted = match.group(1).lower()
        if extracted in ["general", "technical", "aerospace_ste"]:
            profile = extracted

    # 1. Transform prose using controlled dictionary
    transformed_text = apply_lexical_replacements(raw_content, profile=profile)

    # 2. Evaluate resulting text with the compliance engine
    evaluation = evaluate_ste_metrics({
        "profile": profile,
        "text_payload": transformed_text,
        "window_steps": 10
    })

    # 3. Format production output markdown
    output_filename = f"{file_path.stem}.ste.md"
    target_path = OUTPUT_DIR / output_filename

    doc_output = [
        f"<!-- GENERATED BY AEROSTE-CORE BATCH PROCESSOR -->",
        f"<!-- Ingested: {file_path.name} | Profile: {profile} -->",
        f"",
        transformed_text,
        f"",
        f"---",
        f"## STE Audit Verification",
        f"- **Primary Compliance Score**: `{evaluation['primary_metric']} / 100.0`",
        f"- **Readiness State**: `{evaluation['classification']}`",
        f"- **Identified Violations Remaining**: `{len(evaluation['explainability']['violations'])}`",
    ]

    if evaluation["explainability"]["violations"]:
        doc_output.append("\n### Residual Action Items:")
        for v in evaluation["explainability"]["violations"]:
            doc_output.append(f"- Term `{v['term']}` -> Use `{v['approved']}` ({v['rule']})")

    target_path.write_text("\n".join(doc_output), encoding="utf-8")
    print(f"[COMPLETED] Output written to: {target_path} (Score: {evaluation['primary_metric']})")


def main():
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    valid_files = [
        f for f in INPUT_DIR.iterdir()
        if f.is_file() and not f.name.startswith(".") and f.suffix.lower() in [".md", ".txt"]
    ]

    if not valid_files:
        print("[QUEUE] No source documents found in input/.")
        return

    print(f"[QUEUE] Found {len(valid_files)} documents to process.")
    for file_path in valid_files:
        process_file(file_path)


if __name__ == "__main__":
    main()
